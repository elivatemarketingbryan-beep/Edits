// Creates placeholder scene files for any shot that has no scene file yet, plus group index files and src/timeline.js.
import fs from 'node:fs';
import { SHOTS } from '../src/shots.js';
const groups = [...new Set(SHOTS.map((s) => s.group))];
for (const g of groups) {
  const dir = `src/scenes/${g}`; fs.mkdirSync(dir, { recursive: true });
  const ids = SHOTS.filter((s) => s.group === g).map((s) => s.id);
  for (const id of ids) {
    const f = `${dir}/${id}.js`;
    if (fs.existsSync(f)) continue;
    fs.writeFileSync(f, `// PLACEHOLDER — replace with the real scene.
import { shot, WORLDS } from '../../shots.js';
import { placeholder } from '../_placeholder.js';
const S = shot('${id}');
export default { ...S, draw: (ctx, t, s, E) => placeholder(ctx, t, s, S) };
`);
  }
  fs.writeFileSync(`${dir}/index.js`, `// Scenes owned by group ${g}. Order does not matter (timeline sorts by start).\n` +
    ids.map((id) => `import ${id} from './${id}.js';`).join('\n') + `\nexport default [${ids.join(', ')}];\n`);
}
if (false) fs.writeFileSync('src/timeline.js', `// Auto-generated by tools/gen_placeholders.mjs — assembles every group's scenes.\n` +
  groups.map((g) => `import ${g.replace(/\W/g, '_')} from './scenes/${g}/index.js';`).join('\n') +
  `\nexport const DURATION = 165;\nexport const SCENES = [${groups.map((g) => '...' + g.replace(/\W/g, '_')).join(', ')}].sort((a, b) => a.start - b.start);\n`);
console.log('groups', groups.join(' '), 'shots', SHOTS.length);
